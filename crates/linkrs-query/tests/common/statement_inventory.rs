//! Statement-level reachability inventory: one entry per `Stmt` variant.
//!
//! Each entry pins the terminal contract of its variant in the embedded
//! pipeline: either executable with content assertions, explicitly rejected
//! with user-facing guidance, or rejected at parse time. Clause fragments
//! that only occur inside pipes (`Filter`, `Collect`) are exercised through
//! a pipe composition; their `variant` still names the fragment while `kind`
//! names the top-level statement (`PIPE`).
//!
//! The companion `statement_reachability` test asserts that this list and
//! the `Stmt` enum stay in lockstep, so a new variant without an entry
//! fails instead of silently adding a planner dead end.

/// Terminal expectation for one inventory entry.
#[derive(Debug, Clone, Copy)]
pub enum Expectation {
    /// The statement runs to completion in the embedded pipeline.
    Executable {
        /// Expected column names, checked when present.
        columns: Option<&'static [&'static str]>,
        /// Minimum row count in the result.
        min_rows: usize,
    },
    /// The statement fails with a user-facing error. Every guidance
    /// substring must appear in the message, and the message must never
    /// contain the internal planner leak.
    Rejected { guidance: &'static [&'static str] },
    /// The handwritten parser rejects the statement outright.
    ParseRejected,
}

/// One row of the reachability contract.
pub struct InventoryEntry {
    /// `Stmt` variant name, exactly as declared in `stmt.rs`.
    pub variant: &'static str,
    /// SQL text exercising the variant.
    pub sql: &'static str,
    /// DDL setup executed before the probe, in order.
    pub ddl_setup: &'static [&'static str],
    /// DML setup executed after the DDL setup, in order.
    pub dml_setup: &'static [&'static str],
    /// Expected top-level `Stmt::kind()`.
    pub kind: &'static str,
    /// Expected top-level `StmtCategory::as_str()`.
    pub category: &'static str,
    /// Expectation when the required feature (if any) is enabled.
    pub expectation: Expectation,
    /// Cargo feature required for the main expectation (`fulltext`/`vector`).
    pub feature: Option<&'static str>,
    /// Expectation when the required feature is disabled. Applies only when
    /// `feature` is set; setup is skipped in that case.
    pub without_feature: Option<Expectation>,
}

