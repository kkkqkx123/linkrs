// Generate frontend keyword/function tables from the committed inventory.
// Run: npm run gen --prefix tools/grammar-codegen
// Output: frontend/src/lib/utils/generated/{keywords,functions}.ts
// The inventory is produced by:
//   cargo run -p linkrs-query --example export_keyword_inventory
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const inventoryPath = join(root, 'crates', 'linkrs-grammar', 'data', 'keywords.json');
const outDir = join(root, 'frontend', 'src', 'lib', 'utils', 'generated');

const inventory = JSON.parse(readFileSync(inventoryPath, 'utf8'));
const keywords = inventory.keywords.map((entry) => entry.spelling);
const softKeywords = inventory.soft_keywords ?? [];
const operators = inventory.operators ?? [];
const functions = (inventory.functions ?? []).map((func) => ({
	name: func.name,
	arity: func.arity,
	variadic: func.variadic,
	description: func.description,
	category: func.category ?? 'builtin',
}));

const quote = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const keywordsSource = `// auto-generated by tools/grammar-codegen/gen.mjs; do not edit.
export const GENERATED_KEYWORDS: readonly string[] = [
${keywords.map((word) => `\t${quote(word)},`).join('\n')}
];

export const GENERATED_SOFT_KEYWORDS: readonly string[] = [
${softKeywords.map((word) => `\t${quote(word)},`).join('\n')}
];
`;

const operatorsSource = `// auto-generated by tools/grammar-codegen/gen.mjs; do not edit.
export const GENERATED_OPERATORS: readonly string[] = [
${operators.map((entry) => `\t${quote(entry.symbol)},`).join('\n')}
];
`;

const functionsSource = `// auto-generated by tools/grammar-codegen/gen.mjs; do not edit.
export interface GeneratedFunction {
\tname: string;
\tarity: number;
\tvariadic: boolean;
\tdescription: string;
\tcategory: string;
}

export const GENERATED_FUNCTIONS: readonly GeneratedFunction[] = [
${functions.map((func) => `\t{\n\t\tname: ${quote(func.name)},\n\t\tarity: ${func.arity},\n\t\tvariadic: ${func.variadic},\n\t\tdescription: ${quote(func.description)},\n\t\tcategory: ${quote(func.category)},\n\t},`).join('\n')}
];
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'keywords.ts'), keywordsSource);
writeFileSync(join(outDir, 'operators.ts'), operatorsSource);
writeFileSync(join(outDir, 'functions.ts'), functionsSource);
console.log(
	`wrote ${keywords.length} keywords, ${operators.length} operators, ${functions.length} functions to ${outDir}`,
);
